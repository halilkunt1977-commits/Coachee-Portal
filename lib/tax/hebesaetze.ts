export type Hebesatz = { gemeinde: string; land: string; landName: string; hebesatz: number; quelle: string; jahr: number; einwohner: number };

const toHebesatz = ([gemeinde, land, hebesatz, q, einwohner]: Row): Hebesatz => ({ gemeinde, land, landName: LAENDER[land] ?? land, hebesatz, quelle: QUELLEN[q].label, jahr: QUELLEN[q].jahr, einwohner });

/** Schreibweisen angleichen: Umlaute, Abkürzungen wie „a.d.“, Satzzeichen */
export function normalizeOrt(s: string) {
  return s
    .toLowerCase()
    .replace(/ä/g, "ae").replace(/ö/g, "oe").replace(/ü/g, "ue").replace(/ß/g, "ss")
    .normalize("NFD").replace(/[̀-ͯ]/g, "")
    .replace(/\bsankt\b/g, "st")
    .replace(/\b(an der|an dem|am|an|a\. ?d\.?|a\.|i\. ?d\.?|in der|im|i\.|bei|b\.|ob der|o\. ?d\.?|v\. ?d\.?|vor der)\s*/g, " ")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

/** Kurzform ohne Zusatz: „Lauf a.d.Pegnitz“ → „lauf“, „Frankfurt (Oder)“ → „frankfurt“, „Röthenbach/Pegnitz“ → „roethenbach“ */
function kurz(name: string) {
  const ohne = name.split(/[/(,]/)[0];
  // Zusatz beginnt bei „a.d.“, „i.d.“, „b.“ … oder bei „am“, „an der“, „im“, „bei“ …
  const m = ohne.match(/\s(?:(?:a|i|o|v)\.\s?d\.|(?:a|i|b|o|v)\.|(?:an der|am|an|im|in|bei|ob|vor)(?=\s|$))/i);
  return normalizeOrt(m ? ohne.slice(0, m.index) : ohne);
}

const INDEX = ROWS.map((r) => ({ row: r, voll: normalizeOrt(r[0]), kurz: kurz(r[0]) }));

/** Ort aus Freitext wie „90402 Nürnberg“ oder „Lauf an der Pegnitz, Bayern“ heraussuchen. Gibt den besten Treffer und weitere gleichnamige Orte zurück. */
export function findeHebesatz(eingabe: string | null | undefined): { treffer: Hebesatz; weitere: Hebesatz[] } | null {
  const roh = String(eingabe ?? "").replace(/\d{4,5}/g, " ").split(",")[0].trim();
  if (!roh) return null;
  const q = normalizeOrt(roh);
  const qKurz = kurz(roh);
  if (!q) return null;
  let list = INDEX.filter((x) => x.voll === q);
  if (!list.length) list = INDEX.filter((x) => x.kurz === q || x.voll === qKurz);
  if (!list.length && qKurz !== q) list = INDEX.filter((x) => x.kurz === qKurz);
  if (!list.length) return null;
  // Bei gleichnamigen Orten zuerst die größte Stadt
  const sorted = [...list].sort((a, b) => b.row[4] - a.row[4]);
  return { treffer: toHebesatz(sorted[0].row), weitere: sorted.slice(1).map((x) => toHebesatz(x.row)) };
}

