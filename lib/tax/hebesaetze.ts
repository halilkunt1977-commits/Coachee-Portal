/** Steuermesszahl für den Gewerbeertrag (§ 11 Abs. 2 GewStG) */
export const MESSZAHL = 0.035;
/** Freibetrag für natürliche Personen und Personengesellschaften (§ 11 Abs. 1 Nr. 1 GewStG) */
export const FREIBETRAG = 24500;
/** Anrechnung auf die Einkommensteuer: das 4-Fache des Messbetrags (§ 35 EStG), höchstens die gezahlte Gewerbesteuer */
export const ANRECHNUNGSFAKTOR = 4;

export type Gewerbesteuer = { ertrag: number; freibetrag: number; gerundet: number; messbetrag: number; steuer: number; anrechnung: number; belastung: number };

/** Gewerbesteuer und Anrechnung auf die Einkommensteuer. Personenunternehmen mit Freibetrag, Kapitalgesellschaften ohne Freibetrag und ohne Anrechnung. */
export function gewerbesteuer(gewerbeertrag: number, hebesatz: number, personenunternehmen = true): Gewerbesteuer {
  const ertrag = Math.max(0, Number.isFinite(gewerbeertrag) ? gewerbeertrag : 0);
  // Gewerbeertrag auf volle 100 € abrunden, dann Freibetrag abziehen
  const freibetrag = personenunternehmen ? Math.min(FREIBETRAG, Math.floor(ertrag / 100) * 100) : 0;
  const gerundet = Math.max(0, Math.floor(ertrag / 100) * 100 - freibetrag);
  const messbetrag = Math.round(gerundet * MESSZAHL * 100) / 100;
  const steuer = Math.round(messbetrag * (hebesatz / 100) * 100) / 100;
  const anrechnung = personenunternehmen ? Math.min(steuer, Math.round(messbetrag * ANRECHNUNGSFAKTOR * 100) / 100) : 0;
  return { ertrag, freibetrag, gerundet, messbetrag, steuer, anrechnung, belastung: Math.round((steuer - anrechnung) * 100) / 100 };
}
